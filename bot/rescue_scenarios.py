RESCUE_BY_ID: dict[str, RescueScenario] = {s.id: s for s in RESCUE_SCENARIOS}


def rescue_prompt_block(rescue_id: str, name: str) -> str:
    scenario = RESCUE_BY_ID[rescue_id]
    return (
        f"БЫСТРОЕ СПАСЕНИЕ — «{scenario.label}»:\n"
        f"Ситуация: {scenario.prompt.format(name=name)}\n"
        f"ОБЯЗАТЕЛЬНО в тексте сказки: {scenario.must_include.format(name=name)}\n"
        f"Дуга: {scenario.story_beat.format(name=name)}\n"
        f"Избегай: {scenario.avoid}\n"
        "Перепиши как связную сказку — своими словами, без морали и поучений."
    )
