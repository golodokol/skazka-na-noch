def fallback_story(
    mode: str,
    name: str,
    hero: str = "",
    day_context: str = "",
    gender: str = "m",
) -> str:
    template = TEMPLATES.get(mode, TEMPLATES["tired"])
    hero_line = f"Рядом шёл {hero}. " if hero else ""
    day_snippet = day_context.strip() if day_context else "обычный, но хороший"
    g = normalize_gender(gender)
    forms = fallback_forms(g)
    gender_suffix = "а" if g == "f" else ""
    fmt = {
        "name": name,
        "hero_line": hero_line,
        "day_snippet": day_snippet,
        "gender_suffix": gender_suffix,
        **forms,
    }
    if mode == "today":
        text = template.format(**fmt)
    else:
        text = template.format(**fmt)
        if day_context:
            text = (
                f"Сегодня у {name} был такой день: {day_context.strip()}\n\n"
                + text
            )
    return text
