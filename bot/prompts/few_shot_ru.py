def few_shot_band(age: int) -> str:
    if age <= 3:
        return "2-3"
    if age <= 5:
        return "4-5"
    return "6-7"


def few_shot_for_age(age: int) -> str:
    """Блок few-shot для system prompt: образец ритма, не сюжета."""
    try:
        age = int(age)
    except (TypeError, ValueError):
        age = 4
    age = max(2, min(7, age))
    band = few_shot_band(age)
    paragraph = FEW_SHOT_BY_BAND[band]
    return (
        f"ПРИМЕР РИТМА И ПЛОТНОСТИ ПРОЗЫ для возраста {age} ({band}) "
        f"(не копируй сюжет, имена и героев — только стиль чтения вслух):\n"
        f"{paragraph}"
    )
