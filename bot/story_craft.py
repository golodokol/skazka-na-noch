# Завершение «сегодня»-сказки — ротация, не только облачко
DAY_CLOSURE_BY_KEYWORD: list[tuple[tuple[str, ...], str]] = [
    (("ссор", "обид", "друг", "поругал", "обидел"), "узелок на ниточке медленно развязался, и на душе стало тише"),
    (("устал", "устала", "каприз", "садик", "тяжел"), "батарейка-солнышко снова начала светить, когда рядом сели близкие"),
    (("боял", "боялась", "страш", "тревож"), "камушек в кармане стал гладким и тёплым"),
    (("рад", "весел", "хорош", "понрав"), "в кармане тихо светился тёплый камешек — память о хорошем дне"),
    (("скуч", "ждал", "ждала"), "маленький фонарик зажёгся, когда пришли близкие"),
    (("нов", "садик", "детск", "незнаком"), "новая тропинка стала знакомой, а фонарик осветил дорогу домой"),
]

DAY_CLOSURE_DEFAULT = [
    "день сложили в рюкзачок и повесили на крючок у двери сна",
    "волнение уложили на полку, как любимую книгу после чтения",
    "чувство дня стало мягким, как тёплый плед на плечах",
    "мысли потекли медленно, как тихая река к берегу сна",
    "сердце стало тихим, как ночной сад после дождя",
]


def suggest_day_closure(day_context: str, *, seed: int = 0) -> str:
    """Подсказка образа завершения дня — разнообразие, не только облачко."""
    ctx = day_context.strip().lower()
    for keywords, closure in DAY_CLOSURE_BY_KEYWORD:
        if any(k in ctx for k in keywords):
            return closure
    if not ctx:
        ctx = "день"
    idx = abs(hash(f"{ctx}:{seed}")) % len(DAY_CLOSURE_DEFAULT)
    return DAY_CLOSURE_DEFAULT[idx]

