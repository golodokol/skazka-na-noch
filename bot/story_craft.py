# Завершение «сегодня»-сказки — ротация, не только облачко
DAY_CLOSURE_BY_KEYWORD: list[tuple[tuple[str, ...], str]] = [
    (("ссор", "обид", "друг", "поругал", "обидел"), "узелок на ниточке медленно развязался, и на душе стало тише"),
    (("устал", "устала", "каприз", "садик", "тяжел"), "батарейка-солнышко снова начала светить, когда рядом сели близкие"),
    (("боял", "боялась", "страш", "тревож"), "камушек в кармане стал гладким и тёплым"),
    (("рад", "весел", "хорош", "понрав"), "в кармане тихо светился тёплый камешек — память о хорошем дне"),
    (("скуч", "ждал", "ждала"), "маленький фонарик зажёгся, когда пришли близкие"),
    (("нов", "садик", "детск", "незнаком"), "новая тропинка стала знакомой, а фонарик осветил дорогу домой"),
]

DAY_CLOSURE_DEFAULT = [
    "день сложили в рюкзачок и повесили на крючок у двери сна",
    "волнение уложили на полку, как любимую книгу после чтения",
    "чувство дня стало мягким, как тёплый плед на плечах",
    "мысли потекли медленно, как тихая река к берегу сна",
    "сердце стало тихим, как ночной сад после дождя",
]


def suggest_day_closure(day_context: str, *, seed: int = 0) -> str:
    """Подсказка образа завершения дня — разнообразие, не только облачко."""
    ctx = day_context.strip().lower()
    for keywords, closure in DAY_CLOSURE_BY_KEYWORD:
        if any(k in ctx for k in keywords):
            return closure
    if not ctx:
        ctx = "день"
    idx = abs(hash(f"{ctx}:{seed}")) % len(DAY_CLOSURE_DEFAULT)
    return DAY_CLOSURE_DEFAULT[idx]

TODAY_STORY_LOGIC = """
ЛОГИКА «СЕГОДНЯШНИЙ ДЕНЬ» — только для тебя как автора, не в тексте сказки:
Заметки родителя осмысли и перескажи своими словами. В тексте — только сцены, действия, разговоры.
Не пиши «сегодня было», «событие дня», «чувство прошло» — покажи это через действие.

Дуга: мягкий вечер → событие своими словами (что было → как прошло → чем закончилось) →
герой не один, чувство меняется → образ дня «уложили» (из DAY_METAPHOR_MAP) → сон.

Связки в тексте: «сначала», «потом», «когда», «после этого», «поэтому».
Запрещено: цитировать заметку, список фактов, слово «метафора», «облачко» без повода.
Один образ дня — в действии, разный от сказки к сказке.
"""


def today_prompt_block(day_context: str, name: str, *, seed: int = 0) -> str:
    ctx = day_context.strip()
    closure_hint = suggest_day_closure(ctx, seed=seed)
    return f"""=== СЕГОДНЯШНИЙ ДЕНЬ — ЗАМЕТКИ РОДИТЕЛЯ (не цитировать в сказке!) ===
«{ctx}»

Задача: осмыслить этот день для {name} и написать сказку с логикой:
что было → как это проходило → что почувствовал герой → как день мягко завершился перед сном.
Перескажи как автор: своими словами, с причинно-следственными связями, без повтора фраз родителя.

Образ завершения дня (можно развить, не копировать дословно): {closure_hint}.
Не используй «облачко разгладилось», если событие не про обиду — выбери свой образ из DAY_METAPHOR_MAP."""


def age_metaphor_band(age: int) -> str:
    if age <= 3:
        return "2-3"
    if age <= 5:
        return "4-5"
    return "6-7"


def pick_metaphor_for_age(age: int, *, seed: int = 0) -> str:
    """Одна метафора для сказки — без полного каталога в промпте."""
    band = age_metaphor_band(age)
    items = METAPHORS_BY_AGE[band]
    idx = abs(hash(f"{age}:{seed}")) % len(items)
    return items[idx]


def metaphor_weave_guide(metaphor: str) -> str:
    return f"""ОБРАЗ ДЛЯ ЭТОЙ СКАЗКИ (один на всю историю — вплети в действие):
{metaphor}

Плохо: «У неё было взъерошенное облачко на сердце.»
Хорошо: «Она сжала кулачок — внутри будто застрял комочек ваты, колючий и тёплый сразу.»
Образ должен вырасти из сцены, а не быть вставлен сверху."""


def metaphors_for_age(age: int) -> str:
    """Устарело: полный список. Используй pick_metaphor_for_age + metaphor_weave_guide."""
    band = age_metaphor_band(age)
    items = METAPHORS_BY_AGE[band]
    return f"Возраст {age} ({band}): выбери 1–2 метафоры из списка:\n" + "\n".join(
        f"- {m}" for m in items
    )


def propp_arc_for_prompt(hero: str) -> str:
    return PROPP_SLEEP_ARC.format(hero=hero or "добрый зверёк")


def context_blocks_for_prompt(
    *,
    mode: str,
    day_context: str,
    age: int,
    metaphor: str,
) -> str:
    """Условные блоки: одна метафора; карта дня — только при today или day_context."""
    blocks: list[str] = [metaphor_weave_guide(metaphor)]
    if mode == "today" or day_context.strip():
        blocks.append(DAY_METAPHOR_MAP.strip())
    if mode == "today" and day_context.strip():
        blocks.append(TODAY_STORY_LOGIC.strip())
    return "\n\n".join(blocks)
