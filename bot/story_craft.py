# Принципы из сказкотерапии (Зинкевич-Евстигнеева, Строгова, Шорохова, Ткач)
SKAZKO_PRINCIPLES = """
ПРИНЦИПЫ СКАЗКОТЕРАПИИ (ритуал, не лечение):
- Сказка — безопасная дистанция: проблема дня в метафоре, не прямой разговор с ребёнком.
- Герой похож на ребёнка или его друг — ребёнок может «примерить» историю на себя.
- Внешнization: чувство — предмет/погода/зверёк, с которым можно положить спать, а не «победить».
- Помощник рядом — взрослый или добрый персонаж; ребёнок не один.
- Без морали «ты должен», без стыда, без сравнения с другими.
- Повтор и ритм (2–3 повтора образа или звука «ш-ш», «тихо-тихо») — как колыбельная.
- Сенсорность (Шорохова): 1–2 ощущения — тепло, мягкость, запах пледа, тихий звук.
- Игра в сказку: образ «смотрим глазами» допустим, но без экрана и мультиков.
- Вопросы и обсуждение — ПОСЛЕ текста (родитель), в тексте сказки вопросов нет.
- Тип сказки: успокаивающая (tired), с лёгкой дугой (medium), визуально-спокойная (screen_free).
"""

DAY_METAPHOR_MAP = """
ПЕРЕВОД СОБЫТИЙ ДНЯ В МЕТАФОРЫ (выбери одну, не называй проблему прямо):
- поссорился / обиделся → облачко стало взъерошенным → разгладили ветром
- устал / каприз → батарейка- солнышко села → зарядили объятием
- боялся / тревога → маленький камушек в кармане → стал гладким
- не хотел спать → зайчик не ложился → нашёл самую мягкую подушку
- новое место / садик → новая тропинка → проводник-фонарик
- много впечатлений → рюкзак полный → повесили на крючок у двери сна
"""


def age_metaphor_band(age: int) -> str:
    if age <= 3:
        return "2-3"
    if age <= 5:
        return "4-5"
    return "6-7"


def metaphors_for_age(age: int) -> str:
    band = age_metaphor_band(age)
    items = METAPHORS_BY_AGE[band]
    return f"Возраст {age} ({band}): выбери 1–2 метафоры из списка:\n" + "\n".join(
        f"- {m}" for m in items
    )


def propp_arc_for_prompt(hero: str) -> str:
    return PROPP_SLEEP_ARC.format(hero=hero or "добрый зверёк")
